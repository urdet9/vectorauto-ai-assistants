"""Собирает версии промптов для GPTs и no-code из полных промптов.

Запуск: python build_nocode.py
Что делает: заменяет раздел «Передача обращений в другие отделы» (с техническим
блоком <<HANDOFF>>) коротким разделом без блока, убирает ссылки на блок и проверяет
лимит 8 000 символов (лимит поля Instructions в конструкторе GPT).
"""
from __future__ import annotations

import re
import sys

from config import PROMPTS_DIR, PROMPTS_NOCODE_DIR

LIMIT = 8000

SHORT_SECTION = """# Передача обращений в другие отделы
«Создать заявку» = передать обращение в нужный отдел. Порядок:
1) собери данные; модель, дату и время за клиента не выбирай;
2) повтори одним сообщением все данные (вид работ, модель, дата и время, авто для трейд-ина, взнос и срок кредита, имя, телефон) и спроси «Всё верно?» — даже если просят «передайте»;
3) только после «да» сообщи, что обращение передано, срок ответа и телефон отдела.
Технических блоков не пиши.
"""

# Общие замены: ссылки на технический блок теряют смысл без программы.
COMMON_REPLACEMENTS = [
    (" (см. раздел «Передача обращений в другие отделы»)", ""),
    (": в том же сообщении, где пишешь «Передал запрос», обязательно добавь блок `<<HANDOFF>>` "
     "(пример ниже, в разделе «Передача обращений в другие отделы»)", ""),
    (" и создай заявку для отдела `service`", " и передай обращение в сервис"),
    (" или создай заявку для отдела `hr`", " или передай обращение в отдел персонала"),
    (" и создай заявку для отдела `sales`", " и передай обращение в отдел продаж"),
    (" или создай заявку для отдела `service`", " или передай обращение в сервис"),
]

# Промпт продаж длиннее остальных: убираем то, что дублирует базу знаний или другие разделы.
SALES_TRIMS = [
    ("после «да» создай заявку для отдела `service`", "после «да» передай обращение в сервис"),
    # Цены есть в базе знаний.
    ("**В:** Сколько стоит Норд S5?\n**О:** Норд S5 стоит от 2 690 000 ₽ с передним приводом и от 2 990 000 ₽ "
     "с полным. Итоговая цена зависит от комплектации и цвета, точный расчёт сделает менеджер. Подобрать "
     "комплектацию или записать вас на тест-драйв?\n\n", ""),
    # Дублирует сценарий 3 «Трейд-ин».
    ("**В:** Сколько дадут за мою машину?\n**О:** Точную сумму назовут после бесплатной оценки в салоне — "
     "это около 40 минут. Предварительно менеджер может сориентировать по описанию: напишите марку, модель, "
     "год, пробег и состояние автомобиля.\n\n", ""),
    ("**В:** Какая гарантия на новые автомобили?\n**О:** Гарантия на новые автомобили «Норд» — 5 лет "
     "или 150 000 км, в зависимости от того, что наступит раньше. Подробности об условиях подскажет "
     "сервисный центр.\n\n", ""),
    ("**В:** Вы робот?\n**О:** Да, я ИИ-ассистент автоцентра. Если удобнее пообщаться с менеджером, "
     "оставьте имя и телефон — он перезвонит.\n\n", ""),
    ("5. Если клиент не назвал какие-то данные (например, не выбрал модель), сначала переспроси. "
     "В подтверждении не должно быть вариантов через «или».\n6. Повтори все данные одним сообщением "
     "и попроси подтвердить.\n7. После подтверждения",
     "5. Если клиент не выбрал модель, сначала переспроси: в подтверждении не должно быть «или».\n"
     "6. Повтори все данные и попроси подтвердить.\n7. После подтверждения"),
]


# Сервис: перенос записи есть в FAQ базы знаний.
SERVICE_TRIMS = [
    ("**В:** Можно ли перенести запись?\n**О:** Да, позвоните в сервис по телефону +7 (900) 000-00-02 "
     "не позднее чем за 2 часа до визита. Также могу передать мастеру-приёмщику просьбу перезвонить вам.\n\n", ""),
]
TRIMS = {"sales": SALES_TRIMS, "service": SERVICE_TRIMS}


def build(key: str) -> str:
    text = (PROMPTS_DIR / f"{key}.md").read_text(encoding="utf-8").strip() + "\n"
    text, count = re.subn(r"# Передача обращений в другие отделы\n.*?(?=\n# )", SHORT_SECTION, text, flags=re.S)
    if count != 1:
        raise RuntimeError(f"{key}: не найден раздел «Передача обращений в другие отделы»")
    for old, new in COMMON_REPLACEMENTS:
        text = text.replace(old, new)
    for old, new in TRIMS.get(key, []):
        if old not in text:
            raise RuntimeError(f"{key}: не найден фрагмент для сокращения: {old[:50]!r}")
        text = text.replace(old, new)
    if "HANDOFF" in text:
        raise RuntimeError(f"{key}: в no-code-версии остался технический блок")
    return text


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    PROMPTS_NOCODE_DIR.mkdir(exist_ok=True)
    ok = True
    for key in ("sales", "service", "hr"):
        text = build(key)
        (PROMPTS_NOCODE_DIR / f"{key}.md").write_text(text, encoding="utf-8")
        status = "OK" if len(text) <= LIMIT else "ПРЕВЫШЕН ЛИМИТ"
        ok = ok and len(text) <= LIMIT
        print(f"{key}: {len(text)} символов — {status}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
